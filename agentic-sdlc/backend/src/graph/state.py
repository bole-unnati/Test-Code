"""src/graph/state.py — Shared SDLCState flowing through all LangGraph nodes"""
from __future__ import annotations
import os as _os, sys as _sys
_b = _os.path.dirname(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))
if _b not in _sys.path: _sys.path.insert(0, _b)
from typing import Literal, Optional, Annotated
from typing_extensions import TypedDict
from langgraph.graph.message import add_messages
from langchain_core.messages import BaseMessage
from datetime import datetime, timezone
import operator, uuid

SDLCPhase = Literal[
    "init","requirements","design","planning","development",
    "testing","ci_cd","deployment","monitoring","documentation","done","failed",
]

class PhaseEvent(TypedDict):
    phase: str
    status: Literal["started","running","completed","failed","skipped"]
    message: str
    timestamp: str
    artifacts: dict
    tool_calls: list[dict]

class Requirement(TypedDict):
    id: str; title: str; description: str
    type: Literal["functional","non_functional","constraint","assumption"]
    priority: Literal["critical","high","medium","low"]
    acceptance_criteria: list[str]

class DesignArtifact(TypedDict):
    architecture_summary: str
    components: list[dict]
    api_contracts: list[dict]
    data_models: list[dict]
    tech_stack: dict
    adrs: list[dict]

class WorkItem(TypedDict):
    id: str; title: str; description: str
    type: Literal["epic","story","task","bug"]
    priority: str; status: str
    linked_requirements: list[str]
    external_id: Optional[str]
    external_url: Optional[str]

class QualityGate(TypedDict):
    gate_name: str; passed: bool; score: float
    checks: list[dict]; blocking: bool

class SDLCState(TypedDict):
    # Control
    run_id: str
    project_name: str
    current_phase: SDLCPhase
    phase_history: Annotated[list[str], operator.add]
    error_count: int
    abort: bool

    # Input
    raw_requirements_doc: str

    # Messages (agent conversation history)
    messages: Annotated[list[BaseMessage], add_messages]

    # Phase outputs (built up progressively)
    requirements:          list[Requirement]
    design:                Optional[DesignArtifact]
    work_items:            list[WorkItem]
    code_repo_url:         Optional[str]
    code_branch:           Optional[str]
    code_pr_url:           Optional[str]
    test_coverage:         float
    test_passed:           int
    test_failed:           int
    ci_status:             Optional[str]
    ci_url:                Optional[str]
    staging_url:           Optional[str]
    production_url:        Optional[str]
    monitoring_config:     Optional[dict]
    documentation_url:     Optional[str]

    # Generated code artifacts
    generated_files:   list          # files generated by DevelopmentAgent
    test_files:        list          # test files generated by QAAgent
    test_output:       Optional[str] # raw test output from Docker
    image_tag:         Optional[str] # Docker image tag after build

    # Quality gates (append-only)
    quality_gates: Annotated[list[QualityGate], operator.add]

    # Live event stream (append-only — frontend reads these)
    events: Annotated[list[PhaseEvent], operator.add]

    # Metadata
    created_at: str
    updated_at: str
    services_enabled: list[str]


def make_event(phase: str, status: str, message: str,
               artifacts: dict | None = None, tool_calls: list | None = None) -> PhaseEvent:
    return PhaseEvent(
        phase=phase, status=status, message=message,
        timestamp=datetime.now(timezone.utc).isoformat(),
        artifacts=artifacts or {}, tool_calls=tool_calls or [],
    )


def initial_state(raw_doc: str, project_name: str, run_id: str = "") -> SDLCState:
    now = datetime.now(timezone.utc).isoformat()
    return SDLCState(
        run_id=run_id or str(uuid.uuid4()),
        project_name=project_name,
        current_phase="init",
        phase_history=[],
        error_count=0,
        abort=False,
        raw_requirements_doc=raw_doc,
        messages=[],
        requirements=[],
        design=None,
        work_items=[],
        code_repo_url=None,
        code_branch=None,
        code_pr_url=None,
        test_coverage=0.0,
        test_passed=0,
        test_failed=0,
        ci_status=None,
        ci_url=None,
        staging_url=None,
        production_url=None,
        monitoring_config=None,
        documentation_url=None,
        quality_gates=[],
        generated_files=[],
        test_files=[],
        test_output=None,
        image_tag=None,
        events=[make_event("init","started",f"Pipeline started for '{project_name}'")],
        created_at=now,
        updated_at=now,
        services_enabled=[],
    )
