async def _get(url, headers, params=None):
    async with httpx.AsyncClient(timeout=30) as c:
        r = await c.get(url, headers=headers, params=params or {})
        log.info("http.get", url=url, status=r.status_code)
        r.raise_for_status()
        return r.json() if r.content else {}

async def _post(url, headers, body):
    async with httpx.AsyncClient(timeout=30) as c:
        r = await c.post(url, headers=headers, json=body)
        log.info("http.post", url=url, status=r.status_code,
                 content_len=len(r.content), preview=r.text[:200])
        print(f"  [HTTP POST] {url}", flush=True)
        print(f"  [HTTP POST] status={r.status_code}  len={len(r.content)}", flush=True)
        if r.content:
            print(f"  [HTTP POST] response={r.text[:300]}", flush=True)
        r.raise_for_status()
        return r.json() if r.content else {}

async def _put(url, headers, body):
    async with httpx.AsyncClient(timeout=30) as c:
        r = await c.put(url, headers=headers, json=body)
        if r.status_code >= 400:
            print(f"  [HTTP PUT] {r.status_code} {url}", flush=True)
            print(f"  [HTTP PUT] response: {r.text[:300]}", flush=True)
        log.info("http.put", url=url, status=r.status_code)
        r.raise_for_status()
        return r.json() if r.content else {}

async def _patch(url, headers, body):
    async with httpx.AsyncClient(timeout=30) as c:
        r = await c.patch(url, headers=headers, json=body)
        log.info("http.patch", url=url, status=r.status_code)
        r.raise_for_status()
        return r.json() if r.content else {}


