def _mmb():
    return f"{settings.mattermost_url.rstrip('/')}/api/v4"


@tool
async def mattermost_notify(message: str, channel: str = "") -> str:
    """Post a notification to Mattermost — skips gracefully if not configured."""
    mm_url = getattr(settings, "mattermost_url", "") or ""
    mm_tok = getattr(settings, "mattermost_token", "") or ""

    # Skip if Mattermost not configured
    if not mm_url or not mm_tok or mm_url in ("", "http://your-mattermost-url"):
        print(f"  [MATTERMOST] Not configured — skipping notification", flush=True)
        return json.dumps({"status": "skipped", "note": "Mattermost not configured"})

    try:
        ch         = channel or getattr(settings, "mattermost_default_channel", "town-square")
        ch_data    = await _get(f"{_mmb()}/channels/name/{ch}", mattermost_headers())
        channel_id = ch_data.get("id")
        if not channel_id:
            return json.dumps({"status": "skipped", "note": f"Channel '{ch}' not found"})
        r       = await _post(f"{_mmb()}/posts", mattermost_headers(),
                              {"channel_id": channel_id, "message": message})
        post_id = r.get("id", "")
        log.info("mattermost.posted", channel=ch, post_id=post_id)
        return json.dumps({"post_id": post_id, "channel": ch, "status": "posted"})
    except Exception as exc:
        err = str(exc)
        if "connection" in err.lower() or "connect" in err.lower() or "timeout" in err.lower():
            print(f"  [MATTERMOST] Unreachable ({err[:80]}) — skipping", flush=True)
            return json.dumps({"status": "skipped", "note": f"Mattermost unreachable: {err[:80]}"})
        log.error("mattermost.notify_failed", error=err)
        return json.dumps({"error": err})


@tool
async def mattermost_phase_update(phase: str, status: str, details: str = "") -> str:
    """Post a structured SDLC phase update to Mattermost."""
    icons = {"started": "▶", "completed": "✅", "failed": "❌", "waiting": "⏸"}
    icon  = icons.get(status, "ℹ")
    label = phase.replace("_", " ").title()
    msg   = f"### {icon} **{label}** — `{status}`"
    if details:
        msg += f"\n{details}"
    return await mattermost_notify.ainvoke({"message": msg})


