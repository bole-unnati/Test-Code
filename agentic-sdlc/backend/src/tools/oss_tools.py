def _gb():
    return f"{settings.gitea_url.rstrip('/')}/api/v1"


def _gitea_owner() -> str:
    """Return actual repo owner — org if it worked, else personal user login."""
    # _gitea_actual_owner is set dynamically when personal fallback is used
    return getattr(settings, "_gitea_actual_owner", None) or settings.gitea_org


@tool
async def gitea_create_repo(name: str, description: str = "") -> str:
    """
    Get-or-create a Gitea repo. Idempotent — safe to call on every run.
    Checks if repo exists first, reuses it if so, creates it if not.
    Always ensures repo has at least one commit before returning.
    """
    owner = _gitea_owner()

    async def _repo_exists() -> dict | None:
        async with httpx.AsyncClient(timeout=15) as c:
            r = await c.get(f"{_gb()}/repos/{owner}/{name}", headers=gitea_headers())
            return r.json() if r.status_code == 200 else None

    async def _has_commits(repo_owner: str) -> bool:
        async with httpx.AsyncClient(timeout=15) as c:
            r = await c.get(f"{_gb()}/repos/{repo_owner}/{name}/branches",
                            headers=gitea_headers())
            branches = r.json() if r.status_code == 200 else []
            return isinstance(branches, list) and len(branches) > 0

    async def _init_readme(repo_owner: str):
        if await _has_commits(repo_owner):
            print(f"  [GITEA] Repo has commits — no init needed", flush=True)
            return
        print(f"  [GITEA] Empty repo — pushing initial README...", flush=True)
        init_url = f"{_gb()}/repos/{repo_owner}/{name}/contents/README.md"
        readme_txt = f"# {name}" + chr(10) + chr(10) + "Generated by SDLC platform." + chr(10)
        readme_b64 = base64.b64encode(readme_txt.encode()).decode()
        async with httpx.AsyncClient(timeout=30) as c:
            r = await c.post(init_url, headers=gitea_headers(), json={
                "message": "init: initial commit",
                "content": readme_b64,
                "branch":  "main",
            })
            print(f"  [GITEA] Init README: {r.status_code}", flush=True)
            if r.status_code >= 400:
                print(f"  [GITEA] Init error: {r.text[:200]}", flush=True)

    # Check if repo already exists — reuse without any modification
    existing = await _repo_exists()
    if existing:
        real_owner = existing.get("owner", {}).get("login", owner)
        repo_url   = existing.get("html_url", f"{settings.gitea_url}/{real_owner}/{name}")
        clone_url  = existing.get("clone_url", f"{repo_url}.git")
        settings.__dict__["_gitea_actual_owner"] = real_owner
        print(f"  [GITEA] Reusing existing repo: {repo_url}", flush=True)
        await _init_readme(real_owner)
        return json.dumps({"repo_url": repo_url, "clone_url": clone_url,
                           "owner": real_owner, "status": "reused"})

    # Create new repo with auto_init=False (we push README ourselves via POST)
    try:
        r = await _post(f"{_gb()}/user/repos", gitea_headers(), {
            "name": name, "description": description,
            "private": True, "auto_init": False, "default_branch": "main",
        })
        real_owner = r.get("owner", {}).get("login", "") or owner
        repo_url   = r.get("html_url", f"{settings.gitea_url}/{real_owner}/{name}")
        clone_url  = r.get("clone_url", f"{repo_url}.git")
        settings.__dict__["_gitea_actual_owner"] = real_owner
        print(f"  [GITEA] Created new repo: {repo_url}", flush=True)
        log.info("gitea.repo_created", name=name, url=repo_url, owner=real_owner)
        await _init_readme(real_owner)
        return json.dumps({"repo_url": repo_url, "clone_url": clone_url,
                           "owner": real_owner, "status": "created"})
    except Exception as exc:
        log.error("gitea.create_repo_failed", name=name, error=str(exc))
        return json.dumps({"error": str(exc)})


@tool
async def gitea_create_branch(repo: str, branch: str, from_branch: str = "main") -> str:
    """Create a branch in a Gitea repository."""
    try:
        r = await _post(
            f"{_gb()}/repos/{_gitea_owner()}/{repo}/branches", gitea_headers(),
            {"new_branch_name": branch, "old_branch_name": from_branch},
        )
        log.info("gitea.branch_created", repo=repo, branch=branch)
        print(f"  [GITEA] branch '{branch}' created in {repo}", flush=True)
        return json.dumps({"branch": r.get("name", branch), "status": "created"})
    except Exception as exc:
        err = str(exc)
        if "422" in err or "already exists" in err.lower():
            # Branch already exists — that's fine
            print(f"  [GITEA] branch '{branch}' already exists in {repo}", flush=True)
            return json.dumps({"branch": branch, "status": "exists"})
        print(f"  [GITEA] branch creation failed: {err}", flush=True)
        log.error("gitea.create_branch_failed", repo=repo, branch=branch, error=err)
        return json.dumps({"error": err})


@tool
async def gitea_push_file(repo: str, branch: str, file_path: str, content: str, message: str) -> str:
    """Push a file to a Gitea repository (create or update). Handles all edge cases."""
    if not file_path or not file_path.strip():
        return json.dumps({"error": "file_path is empty"})
    if not content or not content.strip():
        return json.dumps({"error": f"content is empty for {file_path}"})

    file_path = file_path.strip().lstrip("/")
    encoded   = base64.b64encode(content.encode()).decode()
    owner     = _gitea_owner()
    base_url  = f"{_gb()}/repos/{owner}/{repo}/contents/{file_path}"

    async def _get_sha_direct(target_branch: str) -> str:
        """Get SHA directly via httpx — no error swallowing."""
        url = f"{base_url}?ref={target_branch}"
        async with httpx.AsyncClient(timeout=30) as c:
            r = await c.get(url, headers=gitea_headers())
            print(f"  [GITEA] GET {file_path}?ref={target_branch} → {r.status_code}", flush=True)
            if r.status_code == 200:
                sha = r.json().get("sha", "")
                print(f"  [GITEA] SHA on '{target_branch}': {sha[:12] if sha else 'none'}", flush=True)
                return sha
            return ""

    async def _push(target_branch: str, sha: str) -> dict | None:
        """
        Push file to Gitea.
        - sha = ""  → POST (create new file)
        - sha = "x" → PUT  (update existing file)
        Some Gitea versions incorrectly return [SHA]:Required for PUT on new files.
        We work around this by using POST for creates and PUT for updates.
        """
        body = {"message": message, "content": encoded, "branch": target_branch}
        async with httpx.AsyncClient(timeout=60) as c:
            if sha:
                # File exists — UPDATE via PUT with SHA
                body["sha"] = sha
                print(f"  [GITEA] PUT(update) {file_path} → {target_branch} sha={sha[:8]}", flush=True)
                r = await c.put(base_url, headers=gitea_headers(), json=body)
            else:
                # File does not exist — CREATE via POST
                print(f"  [GITEA] POST(create) {file_path} → {target_branch}", flush=True)
                r = await c.post(base_url, headers=gitea_headers(), json=body)

            print(f"  [GITEA] {file_path} → {target_branch}: {r.status_code}", flush=True)
            if r.status_code >= 400:
                print(f"  [GITEA] ERROR: {r.text[:300]}", flush=True)
                return None
            resp   = r.json() if r.content else {}
            commit = (resp.get("commit") or {}).get("sha", "") if resp else ""
            print(f"  [GITEA] {file_path}: ✓ {target_branch}", flush=True)
            return {"status": "pushed", "path": file_path,
                    "branch": target_branch, "commit": commit}

    for try_branch in [branch, "main", "master"]:
        sha    = await _get_sha_direct(try_branch)
        result = await _push(try_branch, sha)
        if result:
            log.info("gitea.file_pushed", repo=repo, path=file_path, branch=try_branch)
            return json.dumps(result)

    err = f"Failed to push {file_path} (tried: {branch}, main, master)"
    log.error("gitea.push_file_failed", repo=repo, path=file_path, error=err)
    return json.dumps({"error": err})


