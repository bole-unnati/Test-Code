@tool
async def outline_create_document(title: str, text: str, collection_id: str, parent_document_id: str = "") -> str:
    """Create a wiki document in Outline."""
    try:
        body = {"title": title, "text": text, "publish": True}
        if collection_id:   # empty string causes Outline 400 — only set when valid
            body["collectionId"] = collection_id
        if parent_document_id:
            body["parentDocumentId"] = parent_document_id
        r = await _post(f"{_ob()}/documents.create", outline_headers(), body)
        print(f"  [OUTLINE] create response keys: {list(r.keys()) if r else 'empty'}", flush=True)
        # Outline wraps in "data" but some versions return directly
        d = r.get("data") or r
        if not d or not isinstance(d, dict):
            print(f"  [OUTLINE] unexpected response: {r}", flush=True)
            return json.dumps({"error": f"Unexpected Outline response: {r}"})
        doc_id  = d.get("id","")
        url_path= d.get("url","") or d.get("path","")
        doc_url = f"{settings.outline_url.rstrip('/')}{url_path}" if url_path else ""
        print(f"  [OUTLINE] doc_id={doc_id} url={doc_url}", flush=True)
        log.info("outline.document_created", title=title, id=doc_id, url=doc_url)
        return json.dumps({"document_id": doc_id, "title": d.get("title",title),
                           "url": doc_url, "status": "created"})
    except Exception as exc:
        log.error("outline.create_document_failed", title=title, error=str(exc))
        print(f"  [OUTLINE] ERROR: {exc}", flush=True)
        return json.dumps({"error": str(exc)})


