@tool
def minio_upload_artifact(object_name: str, content: str, content_type: str = "text/plain", bucket: str = "") -> str:
    """Upload a text artifact to MinIO."""
    try:
        from minio import Minio
        raw    = settings.minio_url.replace("http://","").replace("https://","")
        secure = settings.minio_url.startswith("https")
        client = Minio(raw, access_key=settings.minio_access_key, secret_key=settings.minio_secret_key, secure=secure)
        bkt    = bucket or settings.minio_bucket
        if not client.bucket_exists(bkt):
            client.make_bucket(bkt)
        data = content.encode("utf-8")
        client.put_object(bkt, object_name, io.BytesIO(data), length=len(data), content_type=content_type)
        url = f"{settings.minio_url}/{bkt}/{object_name}"
        log.info("minio.uploaded", object=object_name, bucket=bkt, url=url)
        return json.dumps({"url": url, "object": object_name, "bucket": bkt, "status": "uploaded"})
    except Exception as exc:
        log.error("minio.upload_failed", object=object_name, error=str(exc))
        return json.dumps({"error": str(exc)})


