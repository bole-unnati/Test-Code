def _pb():
    # Plane Cloud:    PLANE_URL=https://api.plane.so
    #                 → https://api.plane.so/api/v1/workspaces/{slug}
    # Self-hosted:    PLANE_URL=http://192.168.1.100
    #                 → http://192.168.1.100/api/v1/workspaces/{slug}
    # BOTH use /api/v1/ — the earlier /v1/ variant was wrong
    base = settings.plane_url.rstrip("/")
    slug = settings.plane_workspace_slug
    return f"{base}/api/v1/workspaces/{slug}"


_plane_project_id_cache: str = ""


async def _resolve_plane_project_id(hint: str = "") -> str:
    """Return a valid Plane project UUID — auto-fetches if hint is missing/invalid."""
    global _plane_project_id_cache
    import re as _re
    _uuid = _re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", _re.I)

    if hint and _uuid.match(hint):
        _plane_project_id_cache = hint
        return hint

    if _plane_project_id_cache and _uuid.match(_plane_project_id_cache):
        return _plane_project_id_cache

    try:
        print("  [PLANE] Auto-fetching project list...", flush=True)
        data    = await _get(f"{_pb()}/projects/", plane_headers())
        results = data if isinstance(data, list) else data.get("results", [])
        if results:
            pid  = results[0].get("id", "")
            name = results[0].get("name", "")
            if pid and _uuid.match(pid):
                _plane_project_id_cache = pid
                print(f"  [PLANE] Auto-selected: {name} ({pid})", flush=True)
                log.info("plane.auto_project", id=pid, name=name)
                return pid
        print("  [PLANE] No projects found — check PLANE_WORKSPACE_SLUG", flush=True)
    except Exception as e:
        print(f"  [PLANE] Project lookup failed: {e}", flush=True)
        log.warning("plane.project_lookup_failed", error=str(e))
    return ""


@tool
async def plane_create_issue(project_id: str, title: str, description: str = "", priority: str = "medium") -> str:
    """Create a Plane issue."""
    try:
        real_pid = await _resolve_plane_project_id(project_id or getattr(settings, "plane_project_id", ""))
        if not real_pid:
            return json.dumps({"error": "No Plane project found. Set PLANE_PROJECT_ID in .env or check PLANE_WORKSPACE_SLUG."})
        pmap = {"critical": "urgent", "high": "high", "medium": "medium", "low": "low", "none": "none"}
        r = await _post(
            f"{_pb()}/projects/{real_pid}/issues/", plane_headers(),
            {"name": title, "description_html": f"<p>{description}</p>", "priority": pmap.get(priority.lower(), "medium")},
        )
        issue_id = r.get("id", "")
        seq_id   = r.get("sequence_id", "")
        base     = "https://app.plane.so" if "api.plane.so" in settings.plane_url else settings.plane_url.rstrip("/")
        url      = f"{base}/{settings.plane_workspace_slug}/projects/{real_pid}/issues/{issue_id}"
        log.info("plane.issue_created", title=title, id=issue_id, url=url)
        return json.dumps({"issue_id": issue_id, "external_id": f"ISSUE-{seq_id}", "url": url, "status": "created"})
    except Exception as exc:
        log.error("plane.create_issue_failed", title=title, error=str(exc))
        return json.dumps({"error": str(exc)})


@tool
async def plane_create_cycle(project_id: str, name: str) -> str:
    """Create a sprint cycle in Plane (Pro/Business feature — skipped on free plan)."""
    try:
        real_pid = await _resolve_plane_project_id(project_id or getattr(settings, "plane_project_id", ""))
        if not real_pid:
            return json.dumps({"cycle_id": None, "name": name, "status": "skipped",
                               "note": "No project found"})
        from datetime import datetime, timedelta
        today    = datetime.utcnow().date()
        end_date = today + timedelta(days=14)
        fmt      = "%Y-%m-%d"
        url      = f"{_pb()}/projects/{real_pid}/cycles/"
        # Try with progressively simpler payloads until one works
        for payload in [
            {"name": name, "start_date": today.strftime(fmt), "end_date": end_date.strftime(fmt)},
            {"name": name, "start_date": today.strftime(fmt), "end_date": end_date.strftime(fmt), "description": ""},
            {"name": name},  # minimal — some Plane versions accept this
        ]:
            try:
                r = await _post(url, plane_headers(), payload)
                log.info("plane.cycle_created", name=name, id=r.get("id"), payload=list(payload.keys()))
                return json.dumps({"cycle_id": r.get("id",""), "name": r.get("name",name), "status":"created"})
            except Exception as e:
                if "400" in str(e) or "422" in str(e):
                    print(f"  [PLANE CYCLE] payload {list(payload.keys())} → {e}", flush=True)
                    continue
                raise
        # All attempts failed — cycle is non-critical, skip gracefully
        log.warning("plane.cycle_skipped", name=name)
        return json.dumps({"cycle_id": None, "name": name, "status": "skipped",
                           "note": "Cycle creation not supported with this Plane plan/version"})
    except Exception as exc:
        log.warning("plane.create_cycle_failed", name=name, error=str(exc))
        return json.dumps({"status": "skipped", "note": str(exc)[:100]})


@tool
async def plane_update_issue_status(project_id: str, issue_id: str, state_name: str) -> str:
    """Update a Plane issue status."""
    try:
        real_pid    = await _resolve_plane_project_id(project_id or getattr(settings, "plane_project_id", ""))
        states_data = await _get(f"{_pb()}/projects/{real_pid}/states/", plane_headers())
        states      = states_data.get("results", [])
        matched     = next((s for s in states if state_name.lower() in s.get("name","").lower()), None)
        if not matched:
            return json.dumps({"error": f"State '{state_name}' not found"})
        await _patch(f"{_pb()}/projects/{real_pid}/issues/{issue_id}/", plane_headers(), {"state": matched["id"]})
        log.info("plane.issue_updated", issue_id=issue_id, new_state=matched["name"])
        return json.dumps({"status": "updated", "new_state": matched["name"]})
    except Exception as exc:
        log.error("plane.update_issue_failed", issue_id=issue_id, error=str(exc))
        return json.dumps({"error": str(exc)})


